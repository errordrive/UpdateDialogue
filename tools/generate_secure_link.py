#!/usr/bin/env python3
"""
Generate SecureLinkConfig.java from a remote JSON URL.

What gets baked into the app (the plain URL never appears):
  1. The URL bytes XOR-encoded with a SHA-256 keystream (random salt per build).
  2. The SHA-256 hash of the URL (runtime integrity check).
  3. An RSA public key + a SHA256withRSA signature over the URL bytes
     (runtime authenticity check: a replaced link fails verification
     unless it was signed with the matching private key).

Private key handling:
  - --private-key PATH   use this RSA private key (PEM). Keep it secret,
                         never ship it inside the APK or a public repo.
  - env RSA_PRIVATE_KEY_PEM   same, from an environment variable (CI secret).
  - neither              a temporary RSA-2048 key pair is generated for this
                         build only and the private key is deleted after
                         signing. The build still verifies correctly.

Usage:
  python3 tools/generate_secure_link.py --url "https://pastebin.com/raw/XXXX"
  python3 tools/generate_secure_link.py --url "..." --private-key keys/dialogue_rsa.pem
"""

import argparse
import hashlib
import os
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlparse

DEFAULT_OUT = (
    "app/src/main/java/com/error/updatedialogue/SecureLinkConfig.java"
)


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, **kw)


def rsa_sign_and_public(url_bytes: bytes, private_key_path: str | None):
    """Return (public_key_der_bytes, signature_bytes)."""
    tmpdir = tempfile.mkdtemp(prefix="securelink-")
    tmp = Path(tmpdir)
    try:
        if private_key_path:
            key = Path(private_key_path)
            if not key.is_file():
                sys.exit(f"Private key not found: {private_key_path}")
        elif os.environ.get("RSA_PRIVATE_KEY_PEM"):
            key = tmp / "key.pem"
            key.write_text(os.environ["RSA_PRIVATE_KEY_PEM"])
            key.chmod(0o600)
        else:
            key = tmp / "key.pem"
            run(
                [
                    "openssl", "genpkey",
                    "-algorithm", "RSA",
                    "-pkeyopt", "rsa_keygen_bits:2048",
                    "-out", str(key),
                ]
            )

        pub_der = run(
            ["openssl", "pkey", "-in", str(key), "-pubout", "-outform", "DER"]
        ).stdout

        data_file = tmp / "url.bin"
        data_file.write_bytes(url_bytes)
        sig_file = tmp / "url.sig"
        run(
            [
                "openssl", "dgst", "-sha256",
                "-sign", str(key),
                "-out", str(sig_file),
                str(data_file),
            ]
        )
        return pub_der, sig_file.read_bytes()
    finally:
        # Wipe any temporary key material.
        for p in tmp.glob("*"):
            try:
                p.write_bytes(b"\x00" * max(p.stat().st_size, 1))
                p.unlink()
            except OSError:
                pass
        try:
            tmp.rmdir()
        except OSError:
            pass


def encode_url(url_bytes: bytes, salt: bytes) -> bytes:
    out = bytearray()
    block_index = 0
    while len(out) < len(url_bytes):
        block = hashlib.sha256(salt + block_index.to_bytes(4, "big")).digest()
        for b in block:
            if len(out) >= len(url_bytes):
                break
            out.append(url_bytes[len(out)] ^ b)
        block_index += 1
    return bytes(out)


def java_int_array(name: str, data: bytes) -> str:
    lines = [f"    private static final int[] {name} = {{"]
    for i in range(0, len(data), 12):
        chunk = ", ".join(str(b) for b in data[i : i + 12])
        lines.append(f"            {chunk},")
    lines.append("    };")
    return "\n".join(lines)


JAVA_TEMPLATE = """package com.error.updatedialogue;

import android.util.Base64;

import java.nio.charset.StandardCharsets;
import java.security.KeyFactory;
import java.security.MessageDigest;
import java.security.PublicKey;
import java.security.Signature;
import java.security.spec.X509EncodedKeySpec;
import java.util.Arrays;

/**
 * AUTO-GENERATED by tools/generate_secure_link.py - do not edit by hand.
 *
 * The remote JSON link travels inside one opaque blob (encoded link +
 * SHA-256 hash + RSA public key + SHA256withRSA signature). The link is
 * only used after both the hash and the RSA signature verify. The blob
 * string is replaced at runtime by the in-app generator when a new link
 * is generated, so this class contains no readable link or labels.
 */
final class SecureLinkConfig {

    private static final String BLOB = "__BLOB__";

    private static final int[] S_SHA256 = {111, 116, 125, 17, 14, 9, 10};
    private static final int[] S_RSA = {110, 111, 125};
    private static final int[] S_SIG = {111, 116, 125, 14, 9, 10, 75, 85, 72, 84, 110, 111, 125};

    private SecureLinkConfig() {
    }

    private static String d(int[] values) {
        byte[] out = new byte[values.length];
        for (int i = 0; i < values.length; i++) {
            out[i] = (byte) (values[i] ^ 0x3C);
        }
        return new String(out, StandardCharsets.UTF_8);
    }

    private static byte[] blobBytes() {
        try {
            return Base64.decode(BLOB, Base64.NO_WRAP);
        } catch (Exception e) {
            return new byte[0];
        }
    }

    /** Returns the verified remote JSON link, or "" if verification fails. */
    static String getRemoteUrl() {
        try {
            byte[] blob = blobBytes();
            if (blob.length < 3 || blob[0] != 1) {
                return "";
            }
            int urlLen = ((blob[1] & 0xFF) << 8) | (blob[2] & 0xFF);
            int saltOff = 3;
            int encOff = saltOff + 16;
            int hashOff = encOff + urlLen;
            int pubLenOff = hashOff + 32;
            if (blob.length < pubLenOff + 2) {
                return "";
            }
            int pubLen = ((blob[pubLenOff] & 0xFF) << 8) | (blob[pubLenOff + 1] & 0xFF);
            int pubOff = pubLenOff + 2;
            int sigOff = pubOff + pubLen;
            if (blob.length <= sigOff) {
                return "";
            }
            byte[] salt = Arrays.copyOfRange(blob, saltOff, encOff);
            byte[] encoded = Arrays.copyOfRange(blob, encOff, hashOff);
            byte[] expectedHash = Arrays.copyOfRange(blob, hashOff, pubLenOff);
            byte[] publicKey = Arrays.copyOfRange(blob, pubOff, sigOff);
            byte[] sig = Arrays.copyOfRange(blob, sigOff, blob.length);

            MessageDigest digest = MessageDigest.getInstance(d(S_SHA256));
            byte[] urlBytes = new byte[encoded.length];
            int blockIndex = 0;
            int pos = 0;
            while (pos < encoded.length) {
                digest.reset();
                digest.update(salt);
                digest.update((byte) (blockIndex >>> 24));
                digest.update((byte) (blockIndex >>> 16));
                digest.update((byte) (blockIndex >>> 8));
                digest.update((byte) blockIndex);
                byte[] block = digest.digest();
                for (int i = 0; i < block.length && pos < encoded.length; i++) {
                    urlBytes[pos] = (byte) (encoded[pos] ^ block[i]);
                    pos++;
                }
                blockIndex++;
            }
            digest.reset();
            if (!MessageDigest.isEqual(digest.digest(urlBytes), expectedHash)) {
                return "";
            }
            PublicKey key = KeyFactory.getInstance(d(S_RSA))
                    .generatePublic(new X509EncodedKeySpec(publicKey));
            Signature signature = Signature.getInstance(d(S_SIG));
            signature.initVerify(key);
            signature.update(urlBytes);
            if (!signature.verify(sig)) {
                return "";
            }
            return new String(urlBytes, StandardCharsets.UTF_8);
        } catch (Exception e) {
            return "";
        }
    }

    /** Short fingerprint of the locked link, safe to show in the UI. */
    static String getFingerprint() {
        try {
            byte[] blob = blobBytes();
            int urlLen = ((blob[1] & 0xFF) << 8) | (blob[2] & 0xFF);
            int hashOff = 3 + 16 + urlLen;
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < 4; i++) {
                int v = blob[hashOff + i] & 0xFF;
                sb.append(Character.forDigit(v >> 4, 16));
                sb.append(Character.forDigit(v & 0x0F, 16));
            }
            return sb.toString();
        } catch (Exception e) {
            return "";
        }
    }
}
"""


# ---------------------------------------------------------------------------
# Generated MainActivity call bridge
#
# Every generate run also creates a fresh bootstrap-style bridge class with
# randomized framework-neutral names (package, class and method names all
# change each run) and rewrites the GENERATED-CALL blocks in MainActivity
# to call it. MainActivity therefore contains no direct dialogue call -
# only an ordinary-looking lifecycle/bootstrap call. R8 then obfuscates
# the dialogue internals behind the bridge (only the bridge entry points
# are kept, under their generated names, so the smali snippet stays valid).
# ---------------------------------------------------------------------------

import re

_PKG_FIRST = ["runtime", "core", "platform", "app"]
_PKG_SECOND = ["lifecycle", "bootstrap", "window", "config", "init", "compat"]
_CLASS_PREFIX = ["Window", "Lifecycle", "Display", "Config", "Runtime", "App", "View", "Surface"]
_CLASS_SUFFIX = ["Bootstrap", "Binder", "Bridge", "Initializer", "Compat", "Manager", "Registry"]
_ATTACH = ["attach", "bind", "register", "start", "init", "apply"]
_SAMPLE = ["attachSample", "bindSample", "renderSample", "applySample"]
_DETACH = ["detach", "unbind", "release", "stop"]
_STATUS = ["statusCode", "configTag", "buildTag", "profileTag"]
_RESOLVE = ["resolve", "resolveTarget", "readTarget", "target"]
_TEST = ["test", "check", "preview", "verify"]
_DECOY_PROFILE = ["readDisplayProfile", "measureSurface", "readConfigFlags", "sampleDisplayState"]
_DECOY_TOKEN = ["computeWindowToken", "deriveCompatToken", "buildProfileToken", "mixConfigToken"]

