#!/usr/bin/env python3
"""
Generate SecureLinkConfig.java from a remote JSON URL.

What gets baked into the app (the plain URL never appears):
  1. The URL bytes XOR-encoded with a SHA-256 keystream (random salt per build).
  2. The SHA-256 hash of the URL (runtime integrity check).
  3. An RSA public key + a SHA256withRSA signature over the URL bytes
     (runtime authenticity check: a replaced link fails verification
     unless it was signed with the matching private key).

Private key handling:
  - --private-key PATH   use this RSA private key (PEM). Keep it secret,
                         never ship it inside the APK or a public repo.
  - env RSA_PRIVATE_KEY_PEM   same, from an environment variable (CI secret).
  - neither              a temporary RSA-2048 key pair is generated for this
                         build only and the private key is deleted after
                         signing. The build still verifies correctly.

Usage:
  python3 tools/generate_secure_link.py --url "https://pastebin.com/raw/XXXX"
  python3 tools/generate_secure_link.py --url "..." --private-key keys/dialogue_rsa.pem
"""

import argparse
import hashlib
import os
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlparse

DEFAULT_OUT = (
    "app/src/main/java/com/error/updatedialogue/SecureLinkConfig.java"
)


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, **kw)


def rsa_sign_and_public(url_bytes: bytes, private_key_path: str | None):
    """Return (public_key_der_bytes, signature_bytes)."""
    tmpdir = tempfile.mkdtemp(prefix="securelink-")
    tmp = Path(tmpdir)
    try:
        if private_key_path:
            key = Path(private_key_path)
            if not key.is_file():
                sys.exit(f"Private key not found: {private_key_path}")
        elif os.environ.get("RSA_PRIVATE_KEY_PEM"):
            key = tmp / "key.pem"
            key.write_text(os.environ["RSA_PRIVATE_KEY_PEM"])
            key.chmod(0o600)
        else:
            key = tmp / "key.pem"
            run(
                [
                    "openssl", "genpkey",
                    "-algorithm", "RSA",
                    "-pkeyopt", "rsa_keygen_bits:2048",
                    "-out", str(key),
                ]
            )

        pub_der = run(
            ["openssl", "pkey", "-in", str(key), "-pubout", "-outform", "DER"]
        ).stdout

        data_file = tmp / "url.bin"
        data_file.write_bytes(url_bytes)
        sig_file = tmp / "url.sig"
        run(
            [
                "openssl", "dgst", "-sha256",
                "-sign", str(key),
                "-out", str(sig_file),
                str(data_file),
            ]
        )
        return pub_der, sig_file.read_bytes()
    finally:
        # Wipe any temporary key material.
        for p in tmp.glob("*"):
            try:
                p.write_bytes(b"\x00" * max(p.stat().st_size, 1))
                p.unlink()
            except OSError:
                pass
        try:
            tmp.rmdir()
        except OSError:
            pass


def encode_url(url_bytes: bytes, salt: bytes) -> bytes:
    out = bytearray()
    block_index = 0
    while len(out) < len(url_bytes):
        block = hashlib.sha256(salt + block_index.to_bytes(4, "big")).digest()
        for b in block:
            if len(out) >= len(url_bytes):
                break
            out.append(url_bytes[len(out)] ^ b)
        block_index += 1
    return bytes(out)


def java_int_array(name: str, data: bytes) -> str:
    lines = [f"    private static final int[] {name} = {{"]
    for i in range(0, len(data), 12):
        chunk = ", ".join(str(b) for b in data[i : i + 12])
        lines.append(f"            {chunk},")
    lines.append("    };")
    return "\n".join(lines)


JAVA_TEMPLATE = """package com.error.updatedialogue;

import java.nio.charset.StandardCharsets;
import java.security.KeyFactory;
import java.security.MessageDigest;
import java.security.PublicKey;
import java.security.Signature;
import java.security.spec.X509EncodedKeySpec;

/**
 * AUTO-GENERATED by tools/generate_secure_link.py - do not edit by hand.
 *
 * The remote JSON link is baked in at build time and is NOT stored as a
 * plain string. At runtime the link is only used after BOTH checks pass:
 *   1. SHA-256 of the decoded link matches the baked-in hash.
 *   2. The SHA256withRSA signature verifies against the baked-in RSA
 *      public key (only a link signed with the owner's private key passes).
 * If either check fails, getRemoteUrl() returns "" and no fetch happens.
 */
final class SecureLinkConfig {

    private SecureLinkConfig() {
    }

{arrays}

    private static byte[] toBytes(int[] values) {
        byte[] out = new byte[values.length];
        for (int i = 0; i < values.length; i++) {
            out[i] = (byte) values[i];
        }
        return out;
    }

    private static byte[] decode() {
        byte[] salt = toBytes(SALT);
        byte[] encoded = toBytes(ENCODED_URL);
        byte[] out = new byte[encoded.length];
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            int blockIndex = 0;
            int pos = 0;
            while (pos < encoded.length) {
                digest.reset();
                digest.update(salt);
                digest.update((byte) (blockIndex >>> 24));
                digest.update((byte) (blockIndex >>> 16));
                digest.update((byte) (blockIndex >>> 8));
                digest.update((byte) blockIndex);
                byte[] block = digest.digest();
                for (int i = 0; i < block.length && pos < encoded.length; i++) {
                    out[pos] = (byte) (encoded[pos] ^ block[i]);
                    pos++;
                }
                blockIndex++;
            }
        } catch (Exception e) {
            return new byte[0];
        }
        return out;
    }

    /** Returns the verified remote JSON link, or "" if verification fails. */
    static String getRemoteUrl() {
        try {
            byte[] urlBytes = decode();
            if (urlBytes.length == 0) {
                return "";
            }
            // 1) SHA-256 integrity check.
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] actualHash = digest.digest(urlBytes);
            if (!MessageDigest.isEqual(actualHash, toBytes(URL_SHA256))) {
                return "";
            }
            // 2) RSA authenticity check (SHA256withRSA).
            PublicKey publicKey = KeyFactory.getInstance("RSA")
                    .generatePublic(new X509EncodedKeySpec(toBytes(RSA_PUBLIC_KEY)));
            Signature signature = Signature.getInstance("SHA256withRSA");
            signature.initVerify(publicKey);
            signature.update(urlBytes);
            if (!signature.verify(toBytes(RSA_SIGNATURE))) {
                return "";
            }
            return new String(urlBytes, StandardCharsets.UTF_8);
        } catch (Exception e) {
            return "";
        }
    }

    /** Short fingerprint of the locked link, safe to show in the UI. */
    static String getFingerprint() {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < 4 && i < URL_SHA256.length; i++) {
            sb.append(String.format("%02x", URL_SHA256[i]));
        }
        return sb.toString();
    }
}
"""


# ---------------------------------------------------------------------------
# Generated MainActivity call bridge
#
# Every generate run also creates a fresh bootstrap-style bridge class with
# randomized framework-neutral names (package, class and method names all
# change each run) and rewrites the GENERATED-CALL blocks in MainActivity
# to call it. MainActivity therefore contains no direct dialogue call -
# only an ordinary-looking lifecycle/bootstrap call. R8 then obfuscates
# the dialogue internals behind the bridge (only the bridge entry points
# are kept, under their generated names, so the smali snippet stays valid).
# ---------------------------------------------------------------------------

import re

_PKG_FIRST = ["runtime", "core", "platform", "app"]
_PKG_SECOND = ["lifecycle", "bootstrap", "window", "config", "init", "compat"]
_CLASS_PREFIX = ["Window", "Lifecycle", "Display", "Config", "Runtime", "App", "View", "Surface"]
_CLASS_SUFFIX = ["Bootstrap", "Binder", "Bridge", "Initializer", "Compat", "Manager", "Registry"]
_ATTACH = ["attach", "bind", "register", "start", "init", "apply"]
_SAMPLE = ["attachSample", "bindSample", "renderSample", "applySample"]
_DETACH = ["detach", "unbind", "release", "stop"]
_STATUS = ["statusCode", "configTag", "buildTag", "profileTag"]
_RESOLVE = ["resolve", "resolveTarget", "readTarget", "target"]
_DECOY_PROFILE = ["readDisplayProfile", "measureSurface", "readConfigFlags", "sampleDisplayState"]
_DECOY_TOKEN = ["computeWindowToken", "deriveCompatToken", "buildProfileToken", "mixConfigToken"]

BRIDGE_TEMPLATE = """package __PACKAGE__;

import android.app.Activity;
import android.content.res.Configuration;
import android.os.Build;
import android.util.DisplayMetrics;

import com.error.updatedialogue.UpdateDialogue;

/** Lifecycle bootstrap helpers. AUTO-GENERATED - do not edit by hand. */
public final class __CLASS__ {

    private static volatile long sToken;
    private static volatile int sProfile;

    private __CLASS__() {
    }

    public static void __ATTACH__(Activity activity) {
        if (activity == null) {
            return;
        }
        int profile = __PROFILE__(activity);
        sProfile = profile;
        sToken = __TOKEN__(activity, profile);
        if (Build.VERSION.SDK_INT >= 21) {
            UpdateDialogue.checkAndShow(activity);
        }
    }

    public static void __SAMPLE__(Activity activity) {
        if (activity == null) {
            return;
        }
        sProfile = __PROFILE__(activity);
        UpdateDialogue.show(
                activity,
                "New Update!",
                "Version 2.0 is ready with enhanced features and animations.",
                "DOWNLOAD",
                "https://example.com"
        );
    }

    public static void __DETACH__() {
        UpdateDialogue.dismiss();
    }

    public static String __STATUS__() {
        return UpdateDialogue.getLinkFingerprint();
    }

    public static String __RESOLVE__() {
        return UpdateDialogue.getRemoteUrl(null);
    }

    private static int __PROFILE__(Activity activity) {
        DisplayMetrics metrics = activity.getResources().getDisplayMetrics();
        Configuration config = activity.getResources().getConfiguration();
        int value = metrics.widthPixels * 31 + metrics.heightPixels;
        value = value * 17 + config.orientation;
        value = value * 13 + (int) (metrics.density * 100f);
        return value;
    }

    private static long __TOKEN__(Activity activity, int profile) {
        long token = profile;
        String name = activity.getPackageName();
        if (name != null) {
            for (int i = 0; i < name.length(); i++) {
                token = token * 31 + name.charAt(i);
            }
        }
        token ^= (long) Build.VERSION.SDK_INT << 8;
        return token;
    }
}
"""


def _pick(options):
    return secrets.choice(options)


def generate_bridge(project_root: Path):
    package = f"{_pick(_PKG_FIRST)}.{_pick(_PKG_SECOND)}"
    class_name = _pick(_CLASS_PREFIX) + _pick(_CLASS_SUFFIX)
    methods = {
        "attach": _pick(_ATTACH),
        "sample": _pick(_SAMPLE),
        "detach": _pick(_DETACH),
        "status": _pick(_STATUS),
        "resolve": _pick(_RESOLVE),
        "profile": _pick(_DECOY_PROFILE),
        "token": _pick(_DECOY_TOKEN),
    }
    fqcn = f"{package}.{class_name}"

    bridge_rel = Path("app/src/main/java") / Path(*package.split(".")) / f"{class_name}.java"
    generated_dir = project_root / "generated"
    generated_dir.mkdir(parents=True, exist_ok=True)
    manifest = generated_dir / "bridge-manifest.txt"

    # Remove the previous run's bridge so stale generated classes never pile up.
    if manifest.is_file():
        old_rel = manifest.read_text().strip()
        if old_rel:
            old_file = project_root / old_rel
            if old_file.is_file():
                old_file.unlink()

    source = (
        BRIDGE_TEMPLATE.replace("__PACKAGE__", package)
        .replace("__CLASS__", class_name)
        .replace("__ATTACH__", methods["attach"])
        .replace("__SAMPLE__", methods["sample"])
        .replace("__DETACH__", methods["detach"])
        .replace("__STATUS__", methods["status"])
        .replace("__RESOLVE__", methods["resolve"])
        .replace("__PROFILE__", methods["profile"])
        .replace("__TOKEN__", methods["token"])
    )
    bridge_file = project_root / bridge_rel
    bridge_file.parent.mkdir(parents=True, exist_ok=True)
    bridge_file.write_text(source)
    manifest.write_text(str(bridge_rel) + "\n")

    # Keep only the bridge entry points under their generated names;
    # everything behind them is obfuscated by R8.
    proguard = project_root / "app" / "proguard-generated.pro"
    proguard.write_text(
        "# AUTO-GENERATED by tools/generate_secure_link.py - do not edit by hand.\n"
        f"-keep class {fqcn} {{\n"
        f"    public static void {methods['attach']}(android.app.Activity);\n"
        f"    public static void {methods['sample']}(android.app.Activity);\n"
        f"    public static void {methods['detach']}();\n"
        f"    public static java.lang.String {methods['status']}();\n"
        f"    public static java.lang.String {methods['resolve']}();\n"
        "}\n"
    )

    # Ready-to-paste call snippet (names change on every generate).
    smali_class = "L" + package.replace(".", "/") + f"/{class_name};"
    snippet = generated_dir / "mainactivity-call.txt"
    snippet.write_text(
        "Generated MainActivity call (names regenerate on every generate)\n\n"
        "Java (MainActivity.onCreate):\n"
        f"    {fqcn}.{methods['attach']}(this);\n\n"
        "Smali (MainActivity.onCreate, p0 = this):\n"
        f"    invoke-static {{p0}}, {smali_class}->{methods['attach']}(Landroid/app/Activity;)V\n"
    )
    return fqcn, methods


def rewrite_main_activity(project_root: Path, fqcn: str, methods: dict):
    path = (
        project_root
        / "app/src/main/java/com/error/updatedialogue/MainActivity.java"
    )
    text = path.read_text()
    blocks = {
        "STATUS": [f"        String statusCode = {fqcn}.{methods['status']}();"],
        "TEST": [
            f"                if ({fqcn}.{methods['resolve']}().isEmpty()) {{",
            '                    Toast.makeText(MainActivity.this, "Link verification failed", Toast.LENGTH_SHORT).show();',
            "                    return;",
            "                }",
            '                Toast.makeText(MainActivity.this, "Fetching locked link...", Toast.LENGTH_SHORT).show();',
            f"                {fqcn}.{methods['attach']}(MainActivity.this);",
        ],
        "PREVIEW": [f"                {fqcn}.{methods['sample']}(MainActivity.this);"],
        "STARTUP": [f"        {fqcn}.{methods['attach']}(this);"],
        "TEARDOWN": [f"        {fqcn}.{methods['detach']}();"],
        "EXPORT": [
            f'        String entryClass = "{fqcn}";',
            f'        String entryMethod = "{methods["attach"]}";',
        ],
    }
    for name, lines in blocks.items():
        pattern = re.compile(
            rf"(^[ \t]*// GENERATED-CALL:{name}:START[ \t]*\n).*?([ \t]*// GENERATED-CALL:{name}:END)",
            re.MULTILINE | re.DOTALL,
        )
        replacement = "\\g<1>" + "\n".join(lines) + "\n" + "\\g<2>"
        text, count = pattern.subn(replacement, text, count=1)
        if count != 1:
            sys.exit(f"MainActivity GENERATED-CALL marker missing: {name}")
    path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", required=True, help="Remote JSON URL to lock in")
    parser.add_argument("--out", default=DEFAULT_OUT, help="Output Java file")
    parser.add_argument("--private-key", default=None, help="RSA private key PEM (optional)")
    args = parser.parse_args()

    url = args.url.strip()
    parsed = urlparse(url)
    if parsed.scheme not in ("http", "https") or not parsed.netloc:
        sys.exit(f"Not a valid http(s) URL: {url!r}")
    if parsed.scheme != "https":
        print("WARNING: link is not https - use an https raw JSON link.", file=sys.stderr)

    url_bytes = url.encode("utf-8")
    salt = secrets.token_bytes(16)
    encoded = encode_url(url_bytes, salt)
    url_hash = hashlib.sha256(url_bytes).digest()
    public_der, signature = rsa_sign_and_public(url_bytes, args.private_key)

    arrays = "\n\n".join(
        [
            java_int_array("SALT", salt),
            java_int_array("ENCODED_URL", encoded),
            java_int_array("URL_SHA256", url_hash),
            java_int_array("RSA_PUBLIC_KEY", public_der),
            java_int_array("RSA_SIGNATURE", signature),
        ]
    )
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(JAVA_TEMPLATE.replace("{arrays}", arrays))

    fingerprint = url_hash.hex()[:8]
    print(f"SecureLinkConfig written: {out_path}")
    print(f"Locked link host: {parsed.netloc}  SHA-256 fingerprint: {fingerprint}")

    project_root = Path(__file__).resolve().parent.parent
    fqcn, methods = generate_bridge(project_root)
    rewrite_main_activity(project_root, fqcn, methods)
    print(f"Generated MainActivity call: {fqcn}.{methods['attach']}(this)")
    print("Call snippet: generated/mainactivity-call.txt")


if __name__ == "__main__":
    main()
